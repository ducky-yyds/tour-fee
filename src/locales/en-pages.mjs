const exact = text => messages[String(text).trim()] ?? String(text).trim();
const sentenceParts = (text, depth = 0) => {
  const value = String(text || '').trim();
  if (messages[value] !== undefined) return messages[value];
  if (depth < 2) for (const [pattern, replacement] of patterns) {
    const match = value.match(pattern);
    if (match) return typeof replacement === 'function' ? replacement(...match) : value.replace(pattern, replacement);
  }
  return value.split(/(?<=[。；])\s*/u).map(part => {
    if (messages[part] !== undefined) return messages[part];
    // Sentence fragments can themselves contain a small generated warning.
    if (depth < 2) for (const [pattern, replacement] of patterns) {
      const match = part.match(pattern);
      if (match && !part.startsWith('先扣除跨城交通')) return typeof replacement === 'function' ? replacement(...match) : part.replace(pattern, replacement);
    }
    return part;
  }).join(' ');
};
